import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const INDEX_URL = new URL("../public/data/yugioh-setcode-index.json", import.meta.url);
const OUTPUT_URL = new URL(
  "../src/lib/rapidScan/bundledYugiohSets.generated.ts",
  import.meta.url,
);

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function normalizeName(value) {
  return typeof value === "string" ? value.trim().replace(/\s+/g, " ") : "";
}

function setPrefix(value) {
  if (typeof value !== "string") return "";
  return value.trim().split("-", 1)[0].toUpperCase();
}

export function deriveBundledYugiohSets(index) {
  const records = Array.isArray(index)
    ? index.map((record) => [undefined, record])
    : Object.entries(index ?? {});
  const unique = new Map();

  for (const [key, record] of records) {
    if (!record || typeof record !== "object") continue;
    const prefix = setPrefix(record.setCode ?? key);
    const name = normalizeName(record.setName);
    if (!prefix || !name) continue;

    const dedupeKey = `${prefix}\0${name.toLowerCase()}`;
    const current = unique.get(dedupeKey);
    if (!current || compareText(name, current.name) < 0) {
      unique.set(dedupeKey, { prefix, name });
    }
  }

  return Array.from(unique.values())
    .map(({ prefix, name }) => ({
      id: `${prefix}::${encodeURIComponent(name)}`,
      name,
    }))
    .sort(
      (left, right) =>
        compareText(left.name.toLowerCase(), right.name.toLowerCase()) ||
        compareText(left.name, right.name) ||
        compareText(left.id, right.id),
    );
}

export function renderBundledYugiohSetsModule(sets) {
  return [
    "// Generated by scripts/generate-bundled-yugioh-sets.mjs.",
    "// Do not edit by hand.",
    `export const BUNDLED_YUGIOH_SETS = ${JSON.stringify(sets, null, 2)} as const;`,
    "",
  ].join("\n");
}

async function run() {
  const index = JSON.parse(await readFile(INDEX_URL, "utf8"));
  const expected = renderBundledYugiohSetsModule(
    deriveBundledYugiohSets(index),
  );

  if (process.argv.includes("--check")) {
    const actual = await readFile(OUTPUT_URL, "utf8").catch(() => "");
    if (actual !== expected) {
      throw new Error(
        "Bundled Yu-Gi-Oh set catalog is stale. Run node scripts/generate-bundled-yugioh-sets.mjs",
      );
    }
    return;
  }

  await writeFile(OUTPUT_URL, expected);
}

const invokedPath = process.argv[1]
  ? pathToFileURL(process.argv[1]).href
  : "";
if (invokedPath === import.meta.url) {
  await run();
}
